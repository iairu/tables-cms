/**
 * SSG Build Script for TABLES CMS
 * Generates static HTML files from CMS data for Vercel deployment
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, '..');
const staticDir = join(rootDir, 'static');
const distDir = join(rootDir, 'dist');
const srcDir = join(rootDir, 'src');

// Ensure dist directory exists
if (!existsSync(distDir)) {
  mkdirSync(distDir, { recursive: true });
}

// Copy assets
const assetsDir = join(staticDir, 'assets');
if (existsSync(assetsDir)) {
  const distAssetsDir = join(distDir, 'assets');
  if (!existsSync(distAssetsDir)) {
    mkdirSync(distAssetsDir, { recursive: true });
  }
  copyDirectory(assetsDir, distAssetsDir);
}

// Copy CMS data
const cmsDir = join(staticDir, 'cms');
if (existsSync(cmsDir)) {
  const distCmsDir = join(distDir, 'cms');
  if (!existsSync(distCmsDir)) {
    mkdirSync(distCmsDir, { recursive: true });
  }
  copyDirectory(cmsDir, distCmsDir);
}

// Read CMS data
function loadCMSData() {
  const data = {
    pages: [],
    pageGroups: [],
    blogArticles: [],
    settings: {},
    extensions: {}
  };

  const files = {
    pages: 'pages.json',
    pageGroups: 'pageGroups.json',
    blogArticles: 'blogArticles.json',
    settings: 'settings.json',
    extensions: 'extensions.json'
  };

  for (const [key, file] of Object.entries(files)) {
    const filePath = join(cmsDir, file);
    if (existsSync(filePath)) {
      try {
        const content = readFileSync(filePath, 'utf-8');
        data[key] = JSON.parse(content);
      } catch (e) {
        console.warn(`Failed to load ${file}:`, e.message);
      }
    }
  }

  return data;
}

// Generate HTML template
function generateHTMLTemplate(title, content, cmsData = null) {
  const cmsDataScript = cmsData ? `<script>window.__CMS_DATA__ = ${JSON.stringify(cmsData)}</script>` : '';
  
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
  <meta name="description" content="Generated by TABLES CMS">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.0/css/all.min.css">
  <link rel="stylesheet" href="/assets/css/main.css">
  ${cmsDataScript}
</head>
<body class="theme-default">
  <div id="app">${content}</div>
  <script type="module" src="/assets/js/main.js"></script>
</body>
</html>`;
}

// Generate page HTML from components
function generatePageHTML(page, cmsData) {
  const { name, components = [] } = page;
  
  let html = `<article class="page-content">`;
  
  if (components.length > 0) {
    for (const component of components) {
      html += renderComponent(component, cmsData);
    }
  } else {
    html += `<div class="page-body"><h1>${name}</h1></div>`;
  }
  
  html += `</article>`;
  return html;
}

// Render component based on type
function renderComponent(component, cmsData) {
  const { type, props = {} } = component;
  
  switch (type) {
    case 'hero':
      return `
        <section class="component-hero">
          ${props.image ? `<img src="${props.image}" alt="${props.title || ''}" class="hero-image">` : ''}
          <div class="hero-content">
            <h1 class="hero-title">${props.title || ''}</h1>
            ${props.subtitle ? `<p class="hero-subtitle">${props.subtitle}</p>` : ''}
            ${props.ctaText ? `<a href="${props.ctaLink || '#'}" class="btn btn-primary">${props.ctaText}</a>` : ''}
          </div>
        </section>
      `;
    
    case 'text':
      return `
        <section class="component-text">
          <div class="text-content">${props.content || ''}</div>
        </section>
      `;
    
    case 'image':
      return `
        <section class="component-image">
          <img src="${props.src || ''}" alt="${props.alt || ''}" ${props.caption ? `<figcaption>${props.caption}</figcaption>` : ''}>
        </section>
      `;
    
    case 'video':
      return `
        <section class="component-video">
          <div class="video-wrapper">
            <iframe src="${props.url || ''}" frameborder="0" allowfullscreen></iframe>
          </div>
        </section>
      `;
    
    case 'features':
      return `
        <section class="component-features">
          <h2>${props.title || 'Features'}</h2>
          <div class="features-grid">
            ${(props.items || []).map(item => `
              <div class="feature-card">
                ${item.icon ? `<i class="${item.icon}"></i>` : ''}
                <h3>${item.title || ''}</h3>
                <p>${item.description || ''}</p>
              </div>
            `).join('')}
          </div>
        </section>
      `;
    
    case 'cta':
      return `
        <section class="component-cta">
          <h2>${props.title || ''}</h2>
          <p>${props.description || ''}</p>
          <a href="${props.link || '#'}" class="btn btn-primary">${props.buttonText || 'Get Started'}</a>
        </section>
      `;
    
    case 'blog-list':
      const articles = cmsData?.blogArticles || [];
      return `
        <section class="component-blog-list">
          <h2>${props.title || 'Latest Articles'}</h2>
          <div class="blog-grid">
            ${articles.slice(0, props.limit || 6).map(article => `
              <article class="blog-card">
                <a href="/blog/${article.slug || article.id}">
                  ${article.image ? `<img src="${article.image}" alt="${article.title || ''}">` : ''}
                  <h3>${article.title || 'Untitled'}</h3>
                  <p class="blog-excerpt">${article.excerpt || ''}</p>
                  <span class="blog-date">${new Date(article.createdAt || Date.now()).toLocaleDateString()}</span>
                </a>
              </article>
            `).join('')}
          </div>
        </section>
      `;
    
    default:
      return '';
  }
}

// Generate blog article HTML
function generateBlogArticleHTML(article, cmsData) {
  return `
    <article class="blog-article">
      <header class="article-header">
        ${article.image ? `<img src="${article.image}" alt="${article.title || ''}" class="article-image">` : ''}
        <h1>${article.title || 'Untitled'}</h1>
        <div class="article-meta">
          ${article.author ? `<span class="author"><i class="fas fa-user"></i> ${article.author}</span>` : ''}
          <span class="date"><i class="fas fa-calendar"></i> ${new Date(article.createdAt || Date.now()).toLocaleDateString()}</span>
        </div>
        ${article.excerpt ? `<p class="article-excerpt">${article.excerpt}</p>` : ''}
      </header>
      <div class="article-content">
        ${article.content || ''}
      </div>
    </article>
  `;
}

