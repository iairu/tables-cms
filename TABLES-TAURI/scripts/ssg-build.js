// Generate main JS
function generateMainJS() {
  return `
// TABLES CMS - Runtime JS
(function() {
  'use strict';
  
  // Load CMS data if available
  const cmsData = window.__CMS_DATA__ || null;
  
  // Theme switching
  function setTheme(themeName) {
    document.body.className = 'theme-' + themeName;
    localStorage.setItem('tables-theme', themeName);
  }
  
  // Load saved theme
  const savedTheme = localStorage.getItem('tables-theme') || 'default';
  setTheme(savedTheme);
  
  // Expose CMS data globally for components
  window.TABLES = { cmsData, setTheme };
  
  console.log('TABLES CMS loaded');
})();
`;
}

// Copy directory recursively
function copyDirectory(src, dest) {
  const entries = readdirSync(src, { withFileTypes: true });
  
  for (const entry of entries) {
    const srcPath = join(src, entry.name);
    const destPath = join(dest, entry.name);
    
    if (entry.isDirectory()) {
      if (!existsSync(destPath)) {
        mkdirSync(destPath, { recursive: true });
      }
      copyDirectory(srcPath, destPath);
    } else {
      copyFileSync(srcPath, destPath);
    }
  }
}

// Main build function
function build() {
  console.log('🔨 Starting SSG build...');
  
  const cmsData = loadCMSData();
  console.log('📄 Loaded CMS data:', {
    pages: cmsData.pages.length,
    pageGroups: cmsData.pageGroups.length,
    blogArticles: cmsData.blogArticles.length
  });
  
  // Generate assets
  const assetsDir = join(distDir, 'assets');
  const cssDir = join(assetsDir, 'css');
  const jsDir = join(assetsDir, 'js');
  
  if (!existsSync(cssDir)) mkdirSync(cssDir, { recursive: true });
  if (!existsSync(jsDir)) mkdirSync(jsDir, { recursive: true });
  
  writeFileSync(join(cssDir, 'main.css'), generateMainCSS());
  writeFileSync(join(jsDir, 'main.js'), generateMainJS());
  
  // Generate pages
  const pagesDir = join(distDir, 'pages');
  if (!existsSync(pagesDir)) mkdirSync(pagesDir, { recursive: true });
  
  let pagesGenerated = 0;
  for (const page of cmsData.pages || []) {
    const slug = page.slug || page.id || 'index';
    const html = generatePageHTML(page, cmsData);
    const content = generateHTMLTemplate(page.name || 'Page', html, cmsData);
    
    const filePath = join(distDir, `${slug === 'index' ? 'index' : slug}.html`);
    writeFileSync(filePath, content);
    pagesGenerated++;
  }
  
  // Generate blog articles
  const blogDir = join(distDir, 'blog');
  if (!existsSync(blogDir)) mkdirSync(blogDir, { recursive: true });
  
  let articlesGenerated = 0;
  for (const article of cmsData.blogArticles || []) {
    const slug = article.slug || article.id;
    const html = generateBlogArticleHTML(article, cmsData);
    const content = generateHTMLTemplate(article.title || 'Article', html, cmsData);
    
    const filePath = join(blogDir, `${slug}.html`);
    writeFileSync(filePath, content);
    articlesGenerated++;
  }
  
  // Generate index page if no pages exist
  if (pagesGenerated === 0) {
    const html = `
      <div class="container" style="padding: 80px 20px; text-align: center;">
        <h1 style="font-size: 2.5rem; margin-bottom: 20px;">Welcome to TABLES CMS</h1>
        <p style="font-size: 1.25rem; color: var(--text-light);">
          Start creating pages in the CMS to see them here.
        </p>
      </div>
    `;
    const content = generateHTMLTemplate('Home', html, cmsData);
    writeFileSync(join(distDir, 'index.html'), content);
  }
  
  // Generate blog index
  const blogIndexHtml = `
    <div class="container" style="padding: 80px 20px;">
      <h1 style="font-size: 2.5rem; margin-bottom: 40px; text-align: center;">Blog</h1>
      <div class="blog-grid">
        ${(cmsData.blogArticles || []).map(article => `
          <article class="blog-card">
            <a href="/blog/${article.slug || article.id}">
              ${article.image ? `<img src="${article.image}" alt="${article.title || ''}">` : ''}
              <h3>${article.title || 'Untitled'}</h3>
              <p class="blog-excerpt">${article.excerpt || ''}</p>
              <span class="blog-date">${new Date(article.createdAt || Date.now()).toLocaleDateString()}</span>
            </a>
          </article>
        `).join('')}
      </div>
      ${(cmsData.blogArticles || []).length === 0 ? '<p style="text-align: center; color: var(--text-light);">No articles yet.</p>' : ''}
    </div>
  `;
  writeFileSync(join(blogDir, 'index.html'), generateHTMLTemplate('Blog', blogIndexHtml, cmsData));
  
  console.log('✅ SSG build complete!');
  console.log(`   📄 Pages generated: ${pagesGenerated}`);
  console.log(`   📝 Blog articles: ${articlesGenerated}`);
  console.log(`   📁 Output directory: ${distDir}`);
}

// Run build
build();
